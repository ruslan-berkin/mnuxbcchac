def criteria_for_prompt(scope: Literal["requirement", "set"]) -> str:
    """Закрытый список кодов для вставки в промпт."""
    return "\n".join(
        f"- {c.code} — {c.title}. {c.how_to_check}" for c in CRITERIA.values() if c.scope == scope
    )
